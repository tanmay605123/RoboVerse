export interface ComponentPinDef {
  id: string;
  name: string;
  label?: string;
  type: 'digital' | 'analog' | 'power_5v' | 'power_3v3' | 'gnd' | 'input' | 'output' | 'passive' | 'pwm' | 'i2c' | 'uart';
  x: number; // 2D local X in mm/canvas
  y: number; // 2D local Y in mm/canvas
  z?: number;
  position3D?: [number, number, number]; // 3D local offset [x, y, z] in scene units
  description?: string;
}

export interface ComponentVisualDef {
  id: string;
  name: string;
  category:
    | 'basic'
    | 'microcontroller'
    | 'sensor'
    | 'actuator'
    | 'power'
    | 'passive'
    | 'display'
    | 'ic_driver'
    | 'mechanical'
    | 'prototyping';
  isFreeTier: boolean;
  width: number;
  height: number;
  rotationSnapAngle: number;
  pins: ComponentPinDef[];
  defaultProperties: Record<string, any>;
  svgIcon: string;
  datasheetUrl?: string;
  priceInr: number;
  description: string;
  license: string;
  dimensionsMm: { width: number; height: number; depth: number };
  massG: number;
  model3D: {
    primitive: 'box' | 'cylinder' | 'mesh' | 'compound';
    color: string;
    dimensions: [number, number, number]; // width, height, depth in units
    modelUrl?: string;
  };
}

